class SafeTranslationDict(dict):
    """Dictionary wrapper providing seamless fallback to English for any missing translation key."""
    def __init__(self, primary_dict, fallback_dict):
        super().__init__(primary_dict or {})
        self.fallback_dict = fallback_dict or {}

    def __getitem__(self, key):
        if key in self:
            val = super().__getitem__(key)
            if val is not None and val != "":
                return val
        return self.fallback_dict.get(key, key)

    def get(self, key, default=None):
        if key in self:
            val = super().get(key)
            if val is not None and val != "":
                return val
        if default is not None:
            return self.fallback_dict.get(key, default)
        return self.fallback_dict.get(key, key)

